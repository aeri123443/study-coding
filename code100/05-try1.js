/**
 * p.122 05. 행렬의 곱셈
 * 소요시간: 40m 31s
 * 행렬에 대한 이해 부족
 */

function solution(arr1, arr2) {
    var answer = [];
    let nNum = arr1[0].length;
    // answer[i][k] 추가
    for (let i=0; i<arr1.length; i++) {
        let tempLine = [];
        for (let k=0; k<arr2.length; k++){
            // [i][n] + [n][k]
            let tempAdd = 0;
            for(let n=0; n<nNum; n++){
                let temp = arr1[i][n] * arr2[n][k];
                tempAdd += temp;
            }
            tempLine.push(tempAdd);
        }
        // console.log(tempLine);
        answer.push(tempLine);
    }

    return answer;
}

